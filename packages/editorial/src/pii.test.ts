// CAT-05 — 개인정보 형식(주민등록번호·전화번호·이메일·지번까지 적은 주소) 형식별 견본 시험과 실명 표현(성+이름+'씨'·'님')
import { describe, expect, it } from "vitest";
import { detectPii, detectRealNames } from "./pii";

const kindsIn = (text: string) => detectPii(text).map((m) => m.kind);
const matchesIn = (text: string) => detectPii(text).map((m) => m.match);

describe("주민등록번호 형식", () => {
  it.each([
    ["하이픈", "주민번호 900101-1234567 확인", "900101-1234567"],
    ["붙여 씀", "주민번호 9001011234567 확인", "9001011234567"],
    ["하이픈 앞뒤 공백", "900101 - 2234567", "900101 - 2234567"],
    ["2000년대생(3·4)", "000229-3123456", "000229-3123456"],
    ["외국인등록번호(5~8)", "850315-5123456", "850315-5123456"],
    ["뒷자리 일부 가림", "900101-1******", "900101-1******"],
  ])("%s → 잡는다", (_name, text, expected) => {
    expect(detectPii(text)).toEqual([expect.objectContaining({ kind: "resident_id", match: expected })]);
  });

  it.each([
    ["없는 달(13월)", "991301-1234567"],
    ["앞자리 7자리", "1234567-1234567"],
    ["뒷자리 첫 숫자 9", "900101-9234567"],
    ["뒷자리 전부 가림(생년월일만 남음)", "900101-*******"],
    ["계좌번호 형식", "110-123-456789"],
  ])("%s → 잡지 않는다", (_name, text) => {
    expect(kindsIn(text)).not.toContain("resident_id");
  });
});

describe("전화번호 형식", () => {
  it.each([
    ["휴대전화 하이픈", "010-1234-5678"],
    ["휴대전화 점", "010.1234.5678"],
    ["휴대전화 띄어쓰기", "010 1234 5678"],
    ["휴대전화 붙여 씀", "01012345678"],
    ["국가번호 +82", "+82 10-1234-5678"],
    ["국가번호 +82 하이픈", "+82-10-1234-5678"],
    ["옛 휴대전화 앞자리", "011-123-4567"],
    ["서울 지역번호", "02-123-4567"],
    ["서울 지역번호 8자리", "02-1234-5678"],
    ["괄호 지역번호", "(02) 1234-5678"],
    ["경기 지역번호", "031-123-4567"],
    ["인터넷 전화", "070-1234-5678"],
  ])("%s → 잡는다", (_name, text) => {
    expect(detectPii(`연락처 ${text} 로 문의`)).toEqual([expect.objectContaining({ kind: "phone", match: text })]);
  });

  it.each([
    ["기업 대표번호(개인 번호 아님)", "1588-1234"],
    ["날짜", "2026-10-17"],
    ["공고 번호", "제2026-1015호"],
    ["금액", "1,284억 원"],
    ["비율", "18.4%"],
  ])("%s → 잡지 않는다", (_name, text) => {
    expect(detectPii(text)).toEqual([]);
  });
});

describe("이메일 형식", () => {
  it.each([
    ["기본", "kim.minsu@example.com"],
    ["전각 골뱅이", "kim_minsu＠example.co.kr"],
    ["(at) 표기", "kim(at)example.com"],
    ["[at] 표기와 공백", "kim [at] example.com"],
  ])("%s → 잡는다", (_name, text) => {
    expect(detectPii(`메일 ${text} 로`)).toEqual([expect.objectContaining({ kind: "email", match: text })]);
  });

  it.each([
    ["도메인 끝(.com 등) 없음", "user@localhost"],
    ["골뱅이만", "가온시 @세정과"],
  ])("%s → 잡지 않는다", (_name, text) => {
    expect(kindsIn(text)).not.toContain("email");
  });
});

describe("지번까지 적은 주소 형식", () => {
  it.each([
    ["시·구·동 + 지번", "서울특별시 강남구 역삼동 823-12에 산다", "강남구 역삼동 823-12"],
    ["군·읍·리 + 산 지번", "경기도 화성시 봉담읍 와우리 산12-3 일대", "화성시 봉담읍 와우리 산12-3"],
    ["번지 표기", "가온시 누리구 새빛동 123번지", "누리구 새빛동 123번지"],
    ["동 + 하이픈 지번만", "역삼동 823-12 주택", "역삼동 823-12"],
    ["리 + 산 + 번지", "와우리 산 45번지", "와우리 산 45번지"],
    ["도로명 + 건물번호(시·구 포함)", "가온시 한빛구 중앙로 152 상가", "한빛구 중앙로 152"],
  ])("%s → 잡는다", (_name, text, expected) => {
    expect(detectPii(text)).toEqual([expect.objectContaining({ kind: "address", match: expected })]);
  });

  it.each([
    ["동까지만", "서울 강남구 역삼동 일대"],
    ["개수 표현", "누리구 상가 세 곳, 역삼동 3곳"],
    ["단지 수", "한빛구 새빛동 2개 단지"],
    ["구까지만", "가온시 누리구"],
    ["아파트 동·호수", "101동 1203호"],
    ["기간 표현", "강남구 역삼동 3년 거주"],
  ])("%s → 잡지 않는다", (_name, text) => {
    expect(kindsIn(text)).not.toContain("address");
  });
});

describe("여러 형식이 한 글에 있으면 나온 순서대로 모두", () => {
  it("전화번호와 이메일", () => {
    expect(matchesIn("전화 010-1234-5678, 메일 kim@example.com")).toEqual(["010-1234-5678", "kim@example.com"]);
  });

  it("개인정보가 없는 글은 0건", () => {
    expect(detectPii("납세자는 계약일부터 60일을 세어 취득세를 신고했다.")).toEqual([]);
  });
});

describe("실명으로 보이는 표현 (성 + 이름 + '씨'·'님')", () => {
  it.each([
    ["띄어 쓴 씨", "납세자 김민수 씨는", "김민수 씨"],
    ["붙여 쓴 씨", "김민수씨는 신고했다", "김민수씨"],
    ["님", "이영희 님께 연락했다", "이영희 님"],
    ["두 글자 성", "남궁민수 씨가", "남궁민수 씨"],
    ["외자 이름", "박훈 씨", "박훈 씨"],
  ])("%s → 잡는다", (_name, text, expected) => {
    expect(detectRealNames(text)).toEqual([expected]);
  });

  it.each([
    ["가린 이름(김모 씨)", "김모 씨는"],
    ["호칭 명사(고객님·선생님)", "고객님과 선생님께"],
    ["직함(이장님·사장님)", "이장님과 사장님"],
    ["가족 호칭(어머님)", "어머님께"],
    ["'씨'로 끝나는 낱말(마음씨)", "마음씨가 곱다"],
    ["영문 이니셜", "A씨는"],
    ["성만(김 씨)", "김 씨는"],
  ])("%s → 잡지 않는다", (_name, text) => {
    expect(detectRealNames(text)).toEqual([]);
  });
});
