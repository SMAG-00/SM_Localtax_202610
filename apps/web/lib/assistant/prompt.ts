/** 페이지 맥락을 질문 앞에 붙이는 글 — 경로·제목·분야만 (CHAT-06). 본문은 서버가 공개 뷰에서 읽는다 */
export function contextLine(ctx: { path: string; title?: string; field?: string } | undefined): string {
  if (!ctx) return "";
  const parts = [`열린 페이지 경로: ${ctx.path}`];
  if (ctx.title) parts.push(`제목: ${ctx.title}`);
  if (ctx.field) parts.push(`분야: ${ctx.field}`);
  return `[페이지 맥락] ${parts.join(" · ")}\n`;
}
