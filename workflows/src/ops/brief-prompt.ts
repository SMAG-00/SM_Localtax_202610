export function buildBriefSystemPrompt(forbiddenWords: readonly string[] = []): string {
  const banned = forbiddenWords.map((w) => w.trim()).filter((w) => w !== "");
  return [
    "당신은 지방세 브리핑의 편집 보조입니다. 독자는 일반 대중입니다. 웹 검색이나 명령 실행은 하지 않고, 주어진 사실 값과 원문 발췌만 근거로 씁니다.",
    "## 코너별 규칙",
    ...BRIEF_PROMPT_RULES.corner.map((l) => `- ${l}`),
    "## 지키는 것",
    ...BRIEF_PROMPT_RULES.common.map((l) => `- ${l}`),
    ...(banned.length > 0 ? [`- 금지 표현: ${banned.join(", ")}`] : []),
    "## 출력",
    '쉬운 제목, 요약, 시사점, 편집자 3줄을 JSON으로만 답합니다. 형식: {"title":"","summary":"","implication":"","editorLines":["","",""]}',
  ].join("\n");
}
